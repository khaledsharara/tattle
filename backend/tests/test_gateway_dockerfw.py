from __future__ import annotations

from tattle.gateway import dockerfw

DOCKER = """# Generated by iptables-nft-save v1.8.10 (nf_tables) on Sat Oct 24 10:00:00 2026
*nat
:PREROUTING ACCEPT [0:0]
:POSTROUTING ACCEPT [0:0]
:DOCKER - [0:0]
-A POSTROUTING -s 172.17.0.0/16 ! -o docker0 -j MASQUERADE
COMMIT
*filter
:INPUT ACCEPT [0:0]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
:DOCKER - [0:0]
:DOCKER-USER - [0:0]
-A FORWARD -j DOCKER-USER
-A FORWARD -o docker0 -j DOCKER
{extra}-A DOCKER-USER -j RETURN
COMMIT
"""
EMPTY_LEGACY = "# Warning: iptables-legacy tables present, use iptables-legacy-save to see them\n"
OURS = "-A DOCKER-USER -i eth0 -o eth0 -m comment --comment tattle-gateway -j ACCEPT\n"


def docker(extra: str = "") -> str:
    return DOCKER.replace("{extra}", extra)


def test_parse_save():
    tables = dockerfw.parse_save(docker())
    assert tables["filter"].policies["FORWARD"] == "DROP"
    assert tables["filter"].policies["DOCKER-USER"] == "-"
    assert "-A DOCKER-USER -j RETURN" in tables["filter"].rules


def test_backend_is_the_one_docker_uses():
    assert dockerfw.choose_backend({"nft": docker(), "legacy": ""}) == "nft"
    assert dockerfw.choose_backend({"nft": EMPTY_LEGACY, "legacy": docker()}) == "legacy"
    plain = "*filter\n:INPUT ACCEPT [0:0]\n:FORWARD DROP [0:0]\n-A INPUT -i lo -j ACCEPT\nCOMMIT\n"
    assert dockerfw.choose_backend({"nft": "", "legacy": plain}) == "legacy"  # no Docker: the one with rules
    assert dockerfw.choose_backend({"nft": "", "legacy": ""}) is None


def test_adds_the_rule_once():
    plan = dockerfw.plan({"nft": docker(), "legacy": ""}, "eth0")
    assert plan.chain == "DOCKER-USER" and plan.backend == "nft"
    assert plan.commands == [
        ["iptables-nft", "-w", "5", "-I", "DOCKER-USER", "1", "-i", "eth0", "-o", "eth0", "-m", "comment",
         "--comment", "tattle-gateway", "-j", "ACCEPT"],
    ]  # fmt: skip
    assert dockerfw.plan({"nft": docker(OURS), "legacy": ""}, "eth0").commands == []
    quoted = OURS.replace("tattle-gateway", '"tattle-gateway"')
    assert dockerfw.plan({"nft": docker(quoted), "legacy": ""}, "eth0").commands == []


def test_stale_rules_are_replaced():
    """The interface changed (or a duplicate crept in): delete by comment, then insert."""
    stale = OURS.replace("eth0", "enp1s0")
    plan = dockerfw.plan({"nft": docker(stale + OURS + OURS), "legacy": ""}, "eth0")
    assert plan.commands == [
        ["iptables-nft", "-w", "5", "-D", "DOCKER-USER", "-i", "enp1s0", "-o", "enp1s0", "-m", "comment",
         "--comment", "tattle-gateway", "-j", "ACCEPT"],
        ["iptables-nft", "-w", "5", "-D", "DOCKER-USER", "-i", "eth0", "-o", "eth0", "-m", "comment",
         "--comment", "tattle-gateway", "-j", "ACCEPT"],
    ]  # fmt: skip


def test_rules_left_in_the_other_backend_are_removed():
    """The host moved from iptables-legacy to nft: our old legacy rule must go."""
    leftover = "*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\n:DOCKER-USER - [0:0]\n" + OURS + "COMMIT\n"
    plan = dockerfw.plan({"nft": docker(), "legacy": leftover}, "eth0")
    assert plan.backend == "nft"
    assert plan.commands[0][:4] == ["iptables-legacy", "-w", "5", "-D"]
    assert plan.commands[1][:5] == ["iptables-nft", "-w", "5", "-I", "DOCKER-USER"]


def test_forward_drop_without_docker_uses_forward():
    save = "*filter\n:INPUT ACCEPT [0:0]\n:FORWARD DROP [0:0]\n:OUTPUT ACCEPT [0:0]\nCOMMIT\n"
    plan = dockerfw.plan({"nft": save, "legacy": ""}, "eth0")
    assert plan.chain == "FORWARD"
    assert plan.commands[0][3:6] == ["-I", "FORWARD", "1"]
    # ...and moves to DOCKER-USER once Docker has started.
    moved = dockerfw.plan({"nft": docker(OURS.replace("DOCKER-USER", "FORWARD")), "legacy": ""}, "eth0")
    assert [c[3:5] for c in moved.commands] == [["-D", "FORWARD"], ["-I", "DOCKER-USER"]]


def test_nothing_to_do_when_forwarding_is_not_blocked():
    accept = "*filter\n:INPUT ACCEPT [0:0]\n:FORWARD ACCEPT [0:0]\nCOMMIT\n"
    plan = dockerfw.plan({"nft": accept, "legacy": ""}, "eth0")
    assert plan.chain is None and plan.commands == [] and "nothing needs opening" in plan.detail
    plan = dockerfw.plan({"nft": "", "legacy": ""}, "eth0")  # Docker's nftables backend: no iptables at all
    assert plan.backend is None and plan.commands == []


def test_off_removes_every_rule():
    plan = dockerfw.plan({"nft": docker(OURS), "legacy": docker(OURS)}, None)
    assert [c[0] for c in plan.commands] == ["iptables-nft", "iptables-legacy"]
    assert all(c[3] == "-D" for c in plan.commands)


class FakeIptables:
    def __init__(self, saves: dict[str, str], fail: bool = False):
        self.saves, self.fail = saves, fail
        self.ran: list[list[str]] = []

    def __call__(self, argv):
        if argv[0].endswith("-save"):
            backend = argv[0].split("-")[1]
            return (0, self.saves[backend]) if backend in self.saves else (127, "not found")
        self.ran.append(argv)
        return (4, "iptables: Resource temporarily unavailable.\n") if self.fail else (0, "")


def test_apply_runs_the_plan_and_reports():
    fake = FakeIptables({"nft": docker()})
    state = dockerfw.apply("eth0", fake)
    assert state.ok and state.chain == "DOCKER-USER" and len(fake.ran) == 1
    broken = dockerfw.apply("eth0", FakeIptables({"nft": docker()}, fail=True))
    assert broken.ok is False and "Couldn't update Docker's firewall" in broken.detail
    assert broken.as_dict()["backend"] == "nft"
